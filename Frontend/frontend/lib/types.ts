// Domain types for the freight-management frontend.
// These describe what the UI expects. The backend does not implement these
// entities yet (see Frontend/frontend/docs/api-contracts.md); the demo provider in
// lib/data/demo-data.ts produces data in these shapes.

export type TransportMode = 'sea' | 'air' | 'road' | 'rail';
export type ShipmentDirection = 'import' | 'export' | 'transit';

export type ShipmentStatus =
  | 'booked'
  | 'in_transit'
  | 'arrived'
  | 'customs'
  | 'released'
  | 'out_for_delivery'
  | 'delivered'
  | 'on_hold';

export type MilestoneState = 'done' | 'current' | 'pending';

export interface Milestone {
  label: string;
  state: MilestoneState;
  /** Actual ISO date-time the milestone was reached (done) or started (current). */
  at?: string;
  /** Planned / estimated ISO date-time, when known. */
  plannedAt?: string;
  location?: string;
}

export type Severity = 'low' | 'medium' | 'high';

export interface ShipmentException {
  id: string;
  severity: Severity;
  message: string;
  raisedAt: string;
}

export type DelayReason =
  | 'port_congestion'
  | 'border_queue'
  | 'carrier_schedule'
  | 'customs_query'
  | 'missing_documents'
  | 'permit_pending'
  | 'payment_pending'
  | 'equipment_shortage'
  | 'weather'
  | 'other';

export type DelayStatus = 'open' | 'monitoring' | 'resolved';

/**
 * Whether the customer has been told about a delay. The system sends no
 * notifications; staff record what they did outside the system.
 */
export type CustomerNotificationStatus = 'not_notified' | 'informed_manually' | 'not_required';

export interface DelayAction {
  id: string;
  at: string;
  actor: string;
  note: string;
  /** True for entries the UI generated from a change (e.g. "status changed"). */
  automatic?: boolean;
}

export interface ShipmentDelay {
  id: string;
  reason: DelayReason;
  /** What happened, in the user's words. Never generated by the UI. */
  reasonDetail: string;
  identifiedAt: string;
  severity: Severity;
  /** Label of the milestone the delay affects. */
  milestone: string;
  originalExpectedAt: string;
  /** Empty until a revised date is known; the UI never estimates it. */
  revisedExpectedAt?: string;
  /** When true, the revised date is used as the shipment's current ETA. */
  affectsEta: boolean;
  followUpBy: string;
  status: DelayStatus;
  nextAction?: string;
  notes?: string;
  resolvedAt?: string;
  customerNotification: CustomerNotificationStatus;
  customerNotifiedAt?: string;
  actions: DelayAction[];
  updatedAt: string;
}

export type ShipmentEventKind =
  | 'created'
  | 'updated'
  | 'status_changed'
  | 'milestone_updated'
  | 'delay_recorded'
  | 'delay_updated'
  | 'document';

/** Entry in a shipment's change history. */
export interface ShipmentEvent {
  id: string;
  at: string;
  actor: string;
  kind: ShipmentEventKind;
  message: string;
}

export type CustomsStatus =
  | 'not_started'
  | 'documents_pending'
  | 'lodged'
  | 'assessed'
  | 'duty_paid'
  | 'released'
  | 'query';

export interface CustomsEntry {
  /** Internal reference only. Not a KRA iCMS entry number. */
  entryReference?: string;
  status: CustomsStatus;
  dutyKes?: number;
  updatedAt: string;
}

export interface Shipment {
  reference: string;
  customerId: string;
  customerName: string;
  mode: TransportMode;
  direction: ShipmentDirection;
  status: ShipmentStatus;
  origin: string;
  destination: string;
  carrier: string;
  /** B/L, AWB, CMR or rail consignment number. */
  transportDocRef: string;
  equipment: string;
  cargoDescription: string;
  packages: number;
  weightKg: number;
  /** Estimated time of departure. */
  etd?: string;
  /** Planned estimated time of arrival. A revised ETA comes from delays (lib/metrics.ts `currentEta`). */
  eta: string;
  /** Estimated delivery to the consignee. */
  estimatedDeliveryAt?: string;
  /** Actual time of departure. */
  atd?: string;
  /** Actual time of arrival at the destination. */
  ata?: string;
  /** Actual delivery to the consignee. */
  deliveredAt?: string;
  /** Staff member responsible for the job. */
  assignedTo: string;
  /** Overseas / partner agent: the name of a Party of type 'agent'. */
  agentName?: string;
  /** One of the agent's routes (`AgentRoute.id`), when known. */
  agentRouteId?: string;
  customs: CustomsEntry;
  milestones: Milestone[];
  exceptions: ShipmentException[];
  delays: ShipmentDelay[];
  /** Change history, oldest first. */
  events: ShipmentEvent[];
  createdAt?: string;
  updatedAt: string;
}

export type DocumentType =
  | 'bill_of_lading'
  | 'air_waybill'
  | 'road_consignment_note'
  | 'packing_list'
  | 'commercial_invoice'
  | 'certificate_of_origin'
  | 'import_declaration_form';

export type DocumentStatus = 'missing' | 'received' | 'verified' | 'rejected';

/**
 * Metadata of a file selected in the browser. The file itself is held only in
 * the session store's memory (lib/data/session-store.tsx); it is never uploaded.
 */
export interface DocumentFile {
  name: string;
  sizeBytes: number;
  /** MIME type of the accepted format (lib/document-upload.ts), not the browser-reported one. */
  mimeType: string;
  uploadedAt: string;
  uploadedBy: string;
}

export interface ShipmentDocument {
  id: string;
  shipmentReference: string;
  customerName: string;
  type: DocumentType;
  status: DocumentStatus;
  receivedAt?: string;
  note?: string;
  /** Present only for files selected in this browser session. Demo records have no files. */
  file?: DocumentFile;
  /** When the document was last verified or rejected, and by whom. */
  reviewedAt?: string;
  reviewedBy?: string;
}

export type QuotationStatus =
  | 'draft'
  | 'sent'
  | 'accepted'
  | 'booked'
  | 'declined'
  | 'expired';

export type Currency = 'KES' | 'USD';

export interface QuotationLine {
  id: string;
  description: string;
  /** Up to 3 decimal places (e.g. tonnes or cubic metres). */
  quantity: number;
  /** Unit price in minor units (cents), so totals are exact integers. */
  unitPriceMinor: number;
  /** Tax or levy rate entered by the user, in percent (0–100). The UI does not decide tax treatment. */
  taxRatePercent: number;
}

export type QuotationEventKind = 'created' | 'updated' | 'status_changed' | 'duplicated' | 'linked';

export interface QuotationEvent {
  id: string;
  at: string;
  actor: string;
  kind: QuotationEventKind;
  message: string;
}

export interface Quotation {
  reference: string;
  customerId: string;
  customerName: string;
  /** Overseas / partner agent expected to handle the job (Party name). */
  agentName?: string;
  mode: TransportMode;
  direction: ShipmentDirection;
  origin: string;
  destination: string;
  cargoSummary: string;
  currency: Currency;
  lines: QuotationLine[];
  /** Terms and conditions printed on the quotation. */
  terms?: string;
  /** Internal note, not printed. */
  internalNote?: string;
  /** Stored status. "Expired" is also derived from `validUntil` (lib/quotations.ts `effectiveQuotationStatus`). */
  status: QuotationStatus;
  issuedAt: string;
  validUntil: string;
  /** When staff recorded that it was sent outside the system; unknown for some demo records. */
  sentAt?: string;
  /** Who it was sent to, as recorded by staff. */
  sentTo?: string;
  /** When it was accepted or declined. */
  decidedAt?: string;
  /** Set once the quotation has been converted into, or linked to, a shipment. */
  shipmentReference?: string;
  /** Reference of the quotation this draft was copied from. */
  duplicatedFrom?: string;
  events: QuotationEvent[];
  updatedAt: string;
}

export type PartyType = 'customer' | 'agent' | 'supplier' | 'transporter';

export type AccountStatus = 'active' | 'on_hold' | 'closed';

/** Customer billing profile. Fields not held in the demo data stay undefined and show as "Not recorded". */
export interface BillingProfile {
  contactName: string;
  /** Always a reserved `.example` domain in demo data. */
  email: string;
  phone?: string;
  /** Postal / physical billing address lines. */
  address: string[];
  /** KRA PIN, when recorded. Never generated for demo data. */
  taxPin?: string;
  paymentTermsDays: number;
  currency: Currency;
  accountStatus: AccountStatus;
  /** Agreed credit limit, when recorded. */
  creditLimitKes?: number;
}

/** A lane an agent handles. Derived from demo jobs; not an agreement. */
export interface AgentRoute {
  id: string;
  origin: string;
  destination: string;
  modes: TransportMode[];
  /** Short description of what the agent does on this lane. */
  services: string;
}

export interface Party {
  id: string;
  name: string;
  type: PartyType;
  location: string;
  contactName: string;
  /** Always a reserved `.example` domain in demo data. */
  email: string;
  activeShipments: number;
  outstandingKes?: number;
  /** Customers only. */
  billing?: BillingProfile;
  /** Agents only. */
  routes?: AgentRoute[];
}

export type InvoiceStatus = 'draft' | 'issued' | 'part_paid' | 'paid' | 'overdue';

export interface Invoice {
  number: string;
  customerName: string;
  shipmentReference: string;
  amountKes: number;
  paidKes: number;
  issuedAt: string;
  dueAt: string;
  status: InvoiceStatus;
}

export type PaymentMethod = 'mpesa' | 'bank_transfer' | 'cheque';

export interface Payment {
  id: string;
  invoiceNumber: string;
  customerName: string;
  method: PaymentMethod;
  amountKes: number;
  receivedAt: string;
  reference: string;
  reconciled: boolean;
}

export interface Expense {
  id: string;
  shipmentReference: string;
  description: string;
  payee: string;
  amountKes: number;
  incurredAt: string;
  status: 'pending_approval' | 'approved' | 'paid';
}

export interface ActivityItem {
  id: string;
  at: string;
  actor: string;
  message: string;
  shipmentReference?: string;
  quotationReference?: string;
}

export interface Task {
  id: string;
  title: string;
  dueAt: string;
  priority: Severity;
  assignee: string;
  shipmentReference?: string;
}

/** Where a piece of data came from. Only 'live' means a real backend response. */
export type DataSource = 'demo' | 'live';

export interface Sourced<T> {
  data: T;
  source: DataSource;
}
